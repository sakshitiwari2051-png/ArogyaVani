-- 1. Callers Profile & Health Context (Explicit Consent Principle)
CREATE TABLE IF NOT EXISTS public.callers (
    user_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    language_preference TEXT DEFAULT 'hi',
    consent_given INTEGER DEFAULT 0,
    facts JSONB DEFAULT '{}'::jsonb,
    last_interaction TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_callers_name ON public.callers USING gin (to_tsvector('simple', name));
CREATE INDEX IF NOT EXISTS idx_callers_last_interaction ON public.callers (last_interaction DESC);

-- 2. Human Health-Worker Escalations (Triage & 108 Emergency Handover)
CREATE TABLE IF NOT EXISTS public.escalations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caller_user_id TEXT NOT NULL,
    caller_name TEXT DEFAULT '',
    language TEXT DEFAULT 'hi',
    urgency TEXT DEFAULT 'medium',
    what_happened TEXT NOT NULL,
    already_checked TEXT DEFAULT '',
    followup_method TEXT DEFAULT '',
    callback_phone TEXT DEFAULT '',
    dedupe_key TEXT NOT NULL,
    status TEXT DEFAULT 'open',
    resolution_note TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Partial unique index prevents duplicate open cases for the same caller and trigger
CREATE UNIQUE INDEX IF NOT EXISTS idx_esc_open_dedupe 
ON public.escalations(caller_user_id, dedupe_key) 
WHERE status = 'open';

CREATE INDEX IF NOT EXISTS idx_esc_status_created ON public.escalations(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_esc_caller ON public.escalations(caller_user_id);

-- 3. Live Audio Calls & Telemetry (SIP / WebRTC)
CREATE TABLE IF NOT EXISTS public.calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name TEXT DEFAULT '',
    channel TEXT DEFAULT 'browser',
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ended_at TIMESTAMPTZ,
    duration_secs REAL,
    outcome TEXT DEFAULT 'in_progress',
    outcome_reason TEXT DEFAULT '',
    escalation_created INTEGER DEFAULT 0,
    user_turns INTEGER DEFAULT 0,
    agent_turns INTEGER DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_calls_outcome_started ON public.calls(outcome, started_at DESC);

-- 4. HL7 FHIR R4 Clinical Impressions & NRCeS SOAP Notes
CREATE TABLE IF NOT EXISTS public.clinical_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id BIGINT,
    caller_user_id TEXT NOT NULL,
    caller_name TEXT DEFAULT '',
    triage_urgency TEXT DEFAULT 'ROUTINE',
    chief_complaint TEXT DEFAULT '',
    clinical_summary TEXT DEFAULT '',
    fhir_resource JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_notes_caller_created ON public.clinical_notes(caller_user_id, created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.callers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.escalations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.calls ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clinical_notes ENABLE ROW LEVEL SECURITY;

-- Service Role Full Access Policies (Backend Voice Agent & Admin Server Actions)
DROP POLICY IF EXISTS "Service role full access on callers" ON public.callers;
CREATE POLICY "Service role full access on callers" ON public.callers
    FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service role full access on escalations" ON public.escalations;
CREATE POLICY "Service role full access on escalations" ON public.escalations
    FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service role full access on calls" ON public.calls;
CREATE POLICY "Service role full access on calls" ON public.calls
    FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service role full access on clinical_notes" ON public.clinical_notes;
CREATE POLICY "Service role full access on clinical_notes" ON public.clinical_notes
    FOR ALL TO service_role USING (true) WITH CHECK (true);

-- Allow authenticated and anon read/write via PostgREST with valid API keys
DROP POLICY IF EXISTS "Anon/auth access with API key on callers" ON public.callers;
CREATE POLICY "Anon/auth access with API key on callers" ON public.callers
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon/auth access with API key on escalations" ON public.escalations;
CREATE POLICY "Anon/auth access with API key on escalations" ON public.escalations
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon/auth access with API key on calls" ON public.calls;
CREATE POLICY "Anon/auth access with API key on calls" ON public.calls
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon/auth access with API key on clinical_notes" ON public.clinical_notes;
CREATE POLICY "Anon/auth access with API key on clinical_notes" ON public.clinical_notes
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

